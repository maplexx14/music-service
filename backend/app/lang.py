"""Отсев иностранных по языку/письменности треков.

Библиотека пользователя — русский мем-контент (+ немного англоязычного:
Ace of Base, "gay porn" и т.п.). А скипает он стабильно ИНОСТРАННОЕ:
вьетнамские треки ("... gây nghiện", "phai dấu cuộc tình", "đại mèo"),
и прочий не-латинско-не-кириллический контент. Латиница (английский) НЕ
режется — только явно чужие письменности и вьетнамская диакритика, которых
в русском/английском контенте не бывает, поэтому false-positive'ов нет.
"""
import re

# Диапазоны/символы, однозначно указывающие на НЕ русский и НЕ английский
# контент (в порядке: вьетнамская латиница с диакритикой, спец-буквы
# вьетнамского, CJK, кана, хангыль, тайский, арабский, деванагари, иврит).
_FOREIGN_RE = re.compile(
    "["
    "Ḁ-ỿ"          # Latin Extended Additional — вьетн. тональные гласные (ệ, ấ, ạ…)
    "ĂăĐđƠơƯư"  # Ă ă Đ đ Ơ ơ Ư ư — вьетнамские
    "一-鿿"          # CJK
    "぀-ヿ"          # хирагана/катакана
    "가-힯"          # хангыль
    "฀-๿"          # тайский
    "؀-ۿ"          # арабский
    "ऀ-ॿ"          # деванагари (хинди)
    "֐-׿"          # иврит
    "]"
)


def is_foreign_script(text: str) -> bool:
    """True, если в тексте есть символ явно чужой (не рус/англ) письменности
    или вьетнамская диакритика. Английская латиница таковой НЕ считается."""
    return bool(_FOREIGN_RE.search(text or ""))
