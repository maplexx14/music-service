"""Пользовательский баланс «новые артисты / знакомые» (User.discovery_ratio).

Доля выдачи под НЕЗНАКОМЫХ артистов — вопрос вкуса, а не правильной настройки:
одному нужен «только моё», другому — постоянные открытия. Оба движка
(recommendations.py и flow.py) до этого держали её захардкоженной, каждый своей
константой, поэтому смысл живёт здесь, а не в двух местах:

* 0.0 — только знакомые имена (артисты, по которым есть сигнал юзера);
* 0.2 — дефолт, воспроизводит прежнее поведение (20% explore-слотов в
  recommendations.py и 3 из 15 мест под Last.fm в стандартной порции волны);
* 1.0 — только незнакомые.

Это ЦЕЛЬ, а не гарантия: пул разведки конечен (co-occurrence-соседи, похожие по
треку у Last.fm), и когда его не хватает, места отдаются знакомым — короткая
выдача хуже, чем менее «новая». Обратное тоже верно: у нового юзера знакомых
артистов может не быть вовсе. По той же причине последний резерв обоих движков
(добор, когда знакомого пула не осталось) настройке не подчиняется: там выбор не
между новым и знакомым, а между новым и пустой выдачей.

Одно место, где дефолт МЕНЯЕТ прежнее поведение: у порции волны нестандартного
размера (limit != 15 — в приложении такие не запрашиваются, только у внешних
клиентов и в тестах) гарантированная доля Last.fm была 0.34, теперь она следует
той же настройке. Разъезд был техническим: «столько-то процентов нового» не
должно значить разное в зависимости от размера порции.
"""
from typing import Optional

# Дефолт == прежнее захардкоженное поведение обоих движков, поэтому у юзера,
# который ползунок не трогал, выдача не меняется.
DEFAULT_DISCOVERY_RATIO = 0.2


def discovery_ratio(user) -> float:
    """Доля незнакомых артистов для этого юзера, гарантированно в [0.0, 1.0].

    Читает атрибут защитно: у юзера из старой сессии/фикстуры поля может не
    быть вовсе, а None приходит из строки, созданной до миграции 0015.
    """
    raw: Optional[float] = getattr(user, "discovery_ratio", None)
    if raw is None:
        return DEFAULT_DISCOVERY_RATIO
    try:
        value = float(raw)
    except (TypeError, ValueError):
        return DEFAULT_DISCOVERY_RATIO
    return min(1.0, max(0.0, value))


def discovery_slots(limit: int, ratio: float) -> int:
    """Сколько мест из limit отдать незнакомым артистам.

    Ползунок в нуле означает НОЛЬ таких мест (а не «хотя бы одно»): юзер,
    выключивший разведку, не должен получать её всё равно. Ненулевая доля,
    наоборот, всегда даёт минимум одно место — иначе на порции из 8 треков
    настройка 10% округлялась бы в ничто.
    """
    if limit <= 0 or ratio <= 0:
        return 0
    return min(limit, max(1, round(limit * ratio)))
