import './HeroBolts.css'

// Молнии из логотипа, разбросанные по краям hero (центр занят диском и
// кнопкой потока). x/y — позиция в процентах, s — масштаб, r — наклон,
// v — форма спрайта (те же, что у BoltLoader), d — сдвиг вспышки в долях
// цикла: соседние по экрану молнии бьют не подряд.
const BOLTS = [
  { x: 8, y: 20, s: 1, r: -18, v: 1, d: 0 },
  { x: 24, y: 74, s: 0.8, r: 12, v: 2, d: 0.37 },
  { x: 38, y: 12, s: 0.6, r: 28, v: 3, d: 0.73 },
  { x: 63, y: 82, s: 0.7, r: -24, v: 1, d: 0.19 },
  { x: 80, y: 18, s: 1.1, r: 16, v: 2, d: 0.55 },
  { x: 92, y: 64, s: 0.75, r: -8, v: 3, d: 0.88 },
]

// Фон hero в облегчённом режиме вместо WebGL-градиента. Молнии почти всё
// время неподвижны и раз в цикл «бьют» короткой двойной вспышкой. Между
// вспышками значения анимации не меняются, и браузеру нечего перерисовывать,
// так что фон почти бесплатный даже на слабом железе. Играет поток — грозы
// вдвое больше.
function HeroBolts({ active = false }) {
  return (
    <div className={`hero-bolts${active ? ' is-active' : ''}`} aria-hidden="true">
      {BOLTS.map((b, i) => (
        <i
          key={i}
          className={`hero-bolt v${b.v}`}
          style={{
            left: `${b.x}%`,
            top: `${b.y}%`,
            '--s': b.s,
            '--r': `${b.r}deg`,
            '--d': b.d,
          }}
        />
      ))}
    </div>
  )
}

export default HeroBolts
