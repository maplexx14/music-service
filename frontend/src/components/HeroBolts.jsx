import './HeroBolts.css'

// Точки вспышек по краям hero (центр занят диском и кнопкой потока). x/y —
// точка в процентах, s — масштаб ореола, d — сдвиг вспышки в долях цикла.
// Сдвиги кратны 1/6: вспышки идут ровно через шестую часть цикла, и общая
// подсветка неба (::before в CSS) попадает в каждую.
const BOLTS = [
  { x: 8, y: 20, s: 1, d: 0 },
  { x: 24, y: 74, s: 0.8, d: 3 / 6 },
  { x: 38, y: 12, s: 0.65, d: 1 / 6 },
  { x: 63, y: 82, s: 0.75, d: 4 / 6 },
  { x: 80, y: 18, s: 1.1, d: 2 / 6 },
  { x: 92, y: 64, s: 0.8, d: 5 / 6 },
]

// Фон hero в облегчённом режиме вместо WebGL-градиента. Раз в несколько
// секунд в одной из точек вспыхивает ореол с мерцанием и мягко светлеет
// небо. Самих молний нет — только свет. Анимация идёт только во время
// вспышки (~1 с), между ними браузеру нечего перерисовывать. Играет поток —
// вспышки вдвое чаще.
function HeroBolts({ active = false }) {
  return (
    <div className={`hero-bolts${active ? ' is-active' : ''}`} aria-hidden="true">
      {BOLTS.map((b, i) => (
        <i
          key={i}
          className="hero-bolt"
          style={{
            left: `${b.x}%`,
            top: `${b.y}%`,
            '--s': b.s,
            '--d': b.d,
            '--y': b.y,
          }}
        />
      ))}
    </div>
  )
}

export default HeroBolts
