import './HeroBolts.css'

// Молнии из логотипа. x — колонка падения в процентах ширины, y — где
// молния стоит без анимации (prefers-reduced-motion), s — масштаб, r —
// наклон (небольшой: молния бьёт сверху вниз), v — форма спрайта (те же, что
// у BoltLoader), d — сдвиг падения в долях цикла: соседние колонки падают не
// подряд, и в каждый момент в воздухе одна-две молнии.
const BOLTS = [
  { x: 8, y: 20, s: 1, r: -10, v: 1, d: 0 },
  { x: 24, y: 74, s: 0.8, r: 8, v: 2, d: 0.5 },
  { x: 38, y: 12, s: 0.65, r: 12, v: 3, d: 0.17 },
  { x: 63, y: 82, s: 0.75, r: -12, v: 1, d: 0.67 },
  { x: 80, y: 18, s: 1.1, r: 6, v: 2, d: 0.33 },
  { x: 92, y: 64, s: 0.8, r: -6, v: 3, d: 0.83 },
]

// Фон hero в облегчённом режиме вместо WebGL-градиента. Каждая молния раз в
// цикл быстро падает сверху вниз с ускорением и вспышкой на старте, а
// остальное время её не видно и она стоит — браузеру нечего перерисовывать.
// Непрерывный «снегопад» держал бы композитор занятым всё время, а здесь
// анимируется одна-две маленькие картинки и только transform/opacity. Играет
// поток — молнии падают вдвое чаще.
function HeroBolts({ active = false }) {
  return (
    <div className={`hero-bolts${active ? ' is-active' : ''}`} aria-hidden="true">
      {BOLTS.map((b, i) => (
        <i
          key={i}
          className={`hero-bolt v${b.v}`}
          style={{
            left: `${b.x}%`,
            top: `${b.y}%`,
            '--s': b.s,
            '--r': `${b.r}deg`,
            '--d': b.d,
            '--y': b.y,
          }}
        />
      ))}
    </div>
  )
}

export default HeroBolts
