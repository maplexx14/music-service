import './HeroBolts.css'

// Молнии из логотипа, разбросанные по краям hero (центр занят диском и
// кнопкой потока). x/y — точка в процентах, s — масштаб, r — наклон, v —
// форма спрайта в покое (те же, что у BoltLoader), d — сдвиг удара в долях
// цикла. Сдвиги кратны 1/6: удары идут ровно через шестую часть цикла, и
// общая подсветка неба (::before в CSS) попадает в каждый.
const BOLTS = [
  { x: 8, y: 20, s: 1, r: -18, v: 1, d: 0 },
  { x: 24, y: 74, s: 0.8, r: 12, v: 2, d: 3 / 6 },
  { x: 38, y: 12, s: 0.65, r: 24, v: 3, d: 1 / 6 },
  { x: 63, y: 82, s: 0.75, r: -22, v: 1, d: 4 / 6 },
  { x: 80, y: 18, s: 1.1, r: 14, v: 2, d: 2 / 6 },
  { x: 92, y: 64, s: 0.8, r: -8, v: 3, d: 5 / 6 },
]

// Фон hero в облегчённом режиме вместо WebGL-градиента. Молнии тлеют на
// месте, и раз в несколько секунд одна из них бьёт: вспышка с мерцанием,
// ореол вокруг и мягкая подсветка неба. Анимация идёт только во время удара
// (~1 с), между ударами браузеру нечего перерисовывать. Играет поток — удары
// вдвое чаще.
function HeroBolts({ active = false }) {
  return (
    <div className={`hero-bolts${active ? ' is-active' : ''}`} aria-hidden="true">
      {BOLTS.map((b, i) => (
        <i
          key={i}
          className={`hero-bolt v${b.v}`}
          style={{
            left: `${b.x}%`,
            top: `${b.y}%`,
            '--s': b.s,
            '--r': `${b.r}deg`,
            '--d': b.d,
            '--y': b.y,
          }}
        />
      ))}
    </div>
  )
}

export default HeroBolts
