// Единая точка «следующий трек» для всех кнопок и жестов.
//
// Быстрый переход (подмена на заранее прогретый <audio>, см. audioEngine.swapTo)
// умеет делать только Player: у него элементы, слушатели и handoff. Фуллскрин и
// дизлайк раньше звали store.nextTrack() напрямую — трек менялся через эффект,
// src ставился на активный элемент с нуля, а готовый буфер следующего трека
// выбрасывался (clearStalePreload). Отсюда «то мгновенно, то ~6 секунд»:
// зависело от того, какой кнопкой переключили.
//
// Player регистрирует здесь свой обработчик; остальные зовут skipForward и
// передают фолбэк на случай, когда Player не смонтирован.

let handler = null

export function registerSkipForward(fn) {
  handler = fn
  return () => {
    if (handler === fn) handler = null
  }
}

export function skipForward(fallback) {
  if (handler) return handler()
  return fallback?.()
}

// Смена трека из интерфейса — в колбэке rAF, пока страница на экране.
//
// Замер плавности на iPhone: после play() и подмены элемента главный поток
// 100–300 мс занят работой WebKit — отрисовка в этих кадрах 0–3 мс, наш код —
// единицы мс, а повторный play() однажды сам занял 86 мс. Медиавызов тянет
// за собой задачи медиапроцесса, и шли они раньше кадра: кадр с новым треком
// и стартом доезда карусели ждал их. Колбэки rAF выполняются в начале кадра,
// перед стилями и отрисовкой, а React перерисовывается в микрозадаче сразу
// после колбэка, — так новый трек попадает в этот же кадр, а задачи WebKit
// встают в очередь после него, когда анимации уже ведёт композитор. Звук
// стартует не больше чем на кадр позже. В фоне rAF не идёт — там сразу,
// как раньше.
export function switchTrackInFrame(fn) {
  if (typeof document === 'undefined' || document.hidden || typeof requestAnimationFrame !== 'function') {
    fn()
    return
  }
  requestAnimationFrame(() => fn())
}
